"""Generate constraints/bfo_cco-disjointness-shacl.ttl from the disjointness axioms
(owl:disjointWith and owl:AllDisjointClasses) in the BFO and CCO files that kit.yaml loads
into urn:stardog:bfo_cco:bfo and urn:stardog:bfo_cco:cco (fetched from GitHub).

Usage: python tools/gen_disjointness_shacl.py   (needs rdflib and PyYAML)
"""
from itertools import combinations
from pathlib import Path

import rdflib
import yaml
from rdflib import OWL, RDF, RDFS
from rdflib.collection import Collection

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "constraints" / "bfo_cco-disjointness-shacl.ttl"
SOURCE_GRAPHS = {"urn:stardog:bfo_cco:bfo", "urn:stardog:bfo_cco:cco"}

kit = yaml.safe_load((HERE / "kit.yaml").read_text())
g = rdflib.Graph()
for d in kit["data"]:
    if d.get("graph") in SOURCE_GRAPHS:
        g.parse(d["file"], format="turtle")

pairs = set()
for a, b in g.subject_objects(OWL.disjointWith):
    pairs.add(tuple(sorted((a, b))))
for adc in g.subjects(RDF.type, OWL.AllDisjointClasses):
    for a, b in combinations(Collection(g, g.value(adc, OWL.members)), 2):
        pairs.add(tuple(sorted((a, b))))


def curie(u):
    s = str(u)
    for pfx, ns in (("obo", "http://purl.obolibrary.org/obo/"), ("cco", "https://www.commoncoreontologies.org/")):
        if s.startswith(ns):
            return f"{pfx}:{s[len(ns):]}"
    return f"<{s}>"


def label(u):
    return str(g.value(u, RDFS.label) or u)


lines = [
    "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
    "@prefix sh: <http://www.w3.org/ns/shacl#> .",
    "@prefix obo: <http://purl.obolibrary.org/obo/> .",
    "@prefix cco: <https://www.commoncoreontologies.org/> .",
    "@prefix bfo_cco: <urn:stardog:bfo_cco#> .",
    "",
    f"# GENERATED by tools/gen_disjointness_shacl.py from the BFO and CCO files in kit.yaml — do not edit by hand.",
    f"# One shape per disjoint class pair ({len(pairs)} pairs). An instance of both classes",
    "# is a BFO/CCO modeling error (e.g. something typed as both a continuant and an occurrent).",
    "# Validate with reasoning on so subclass instances are included.",
    "",
]
for a, b in sorted(pairs, key=lambda p: (curie(p[0]), curie(p[1]))):
    la, lb = label(a), label(b)
    name = f"{curie(a).split(':', 1)[1]}_{curie(b).split(':', 1)[1]}"
    lines += [
        f"bfo_cco:Disjoint_{name} a sh:NodeShape ;",
        f'    rdfs:label "{la} / {lb} disjointness" ;',
        f"    sh:targetClass {curie(a)} ;",
        f"    sh:not [ sh:class {curie(b)} ] ;",
        "    sh:severity sh:Violation ;",
        f'    sh:message "Instance of {la} is also an instance of {lb}; the two classes are disjoint." .',
        "",
    ]

OUT.write_text("\n".join(lines))
print(f"wrote {OUT} ({len(pairs)} shapes)")
